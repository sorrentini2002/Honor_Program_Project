class LoRaWAN_Network:
    def __init__(self, lista_nodi_iot, tx_interval=600):
        self.env = simpy.Environment()
        self.gateway = Gateway(self.env)
        self.nodes = []
        self.tx_interval = tx_interval

        print("\n📡 INIZIALIZZAZIONE RETE LoRaWAN...")
        for i, node_id in enumerate(lista_nodi_iot):
            sf = random.choice([7, 8, 9, 10, 11, 12])
            node = SensorNode(self.env, node_id, self.gateway, sf, self.tx_interval)
            self.nodes.append(node)
            print(f"   [+] Sensore accoppiato a {node_id} (SF: {sf})")

    def run_communication_step(self, time_step):
        target_time = self.env.now + time_step
        self.env.run(until=target_time)
        return self.gateway.get_and_clear_buffer()

class Gateway:
    def __init__(self, env):
        self.env = env
        self.received_packets = []
        self.active_transmissions = []
        self.stat_totale_inviati = 0
        self.stat_totale_persi = 0

    def receive_uplink(self, packet, time_on_air):
        self.stat_totale_inviati += 1
        self.active_transmissions.append(packet)
        yield self.env.timeout(time_on_air)

        collision = len(self.active_transmissions) > 1
        if not collision:
            self.received_packets.append(packet)
        else:
            self.stat_totale_persi += 1

        self.active_transmissions.remove(packet)

    def get_packet_loss_rate(self):
        if self.stat_totale_inviati == 0:
            return 0.0
        return (self.stat_totale_persi / self.stat_totale_inviati) * 100.0

    def get_and_clear_buffer(self):
        data = self.received_packets.copy()
        self.received_packets.clear()
        return data

class SensorNode:
    def __init__(self, env, node_id, gateway, sf, tx_interval):
        self.env = env
        self.node_id = node_id
        self.gateway = gateway
        self.sf = sf
        self.tx_interval = tx_interval
        self.current_pressure = 0.0
        self.time_on_air = (2 ** sf) / 125000.0 * 20
        self.env.process(self.transmit_loop())

    def update_sensor_data(self, pressure):
        self.current_pressure = pressure

    def aggiorna_intervallo(self, nuovo_intervallo):
        if self.tx_interval != nuovo_intervallo:
            self.tx_interval = nuovo_intervallo

    def transmit_loop(self):
        yield self.env.timeout(random.uniform(0, self.tx_interval))
        while True:
            packet = {
                'node_id': self.node_id,
                'data': self.current_pressure,
                'timestamp': self.env.now
            }
            self.env.process(self.gateway.receive_uplink(packet, self.time_on_air))
            yield self.env.timeout(self.tx_interval)

