class AgenteAdattivo:
    def __init__(self, lista_valvole, soglia_critica=20.0):
        self.soglia_critica = soglia_critica
        self.lista_valvole = lista_valvole

        # Stato iniziale: Pressione ottima, Valvole chiuse, Intervallo lungo (Risparmio Rete)
        self.stato_percepito = {
            v: {'pressione': 50.0, 'timestamp': 0.0, 'tx_interval': 3600} for v in lista_valvole
        }
        self.stato_attuatori = {v: 'CLOSED' for v in lista_valvole}

    def elabora_uplink(self, pacchetti_ricevuti):
        """Aggiorna lo stato percepito con i pacchetti sopravvissuti alle collisioni"""
        for p in pacchetti_ricevuti:
            valvola_id = p['node_id']
            self.stato_percepito[valvola_id]['pressione'] = p['data']
            self.stato_percepito[valvola_id]['timestamp'] = p['timestamp']

    def calcola_intervallo_ottimale(self, pressione):
        """
        Funzione Obiettivo Semplificata:
        - Pressione Alta (Sicura) -> Trasmetti poco (es. 3600s / 1 ora) -> Meno Collisioni
        - Pressione in Calo (Attenzione) -> Trasmetti medio (es. 600s / 10 min)
        - Pressione Critica (Emergenza) -> Trasmetti tantissimo (es. 60s / 1 min) -> Rischio Collisioni, ma vitale.
        """
        if pressione > (self.soglia_critica + 20):  # Es: > 40m
            return 3600
        elif pressione > (self.soglia_critica + 5):   # Es: tra 25m e 40m
            return 600
        else:                                         # Es: < 25m (Crisi imminente o in corso)
            return 60

    def valuta_e_decidi(self, current_time):
        """Genera comandi fisici (Valvole) e comandi di rete (MAC commands per LoRa)"""
        comandi_downlink = {}

        for valvola_id, memoria in self.stato_percepito.items():
            pressione = memoria['pressione']
            stato_attuale = self.stato_attuatori[valvola_id]
            intervallo_attuale = memoria['tx_interval']

            # 1. OTTIMIZZAZIONE INTERVALLO (Ricalcolo dinamico)
            nuovo_intervallo = self.calcola_intervallo_ottimale(pressione)

            # Inizializziamo il dizionario dei comandi per questa valvola
            comandi_downlink[valvola_id] = {'azione_valvola': None, 'nuovo_tx': None}

            if nuovo_intervallo != intervallo_attuale:
                comandi_downlink[valvola_id]['nuovo_tx'] = nuovo_intervallo
                self.stato_percepito[valvola_id]['tx_interval'] = nuovo_intervallo
                print(f"📡 AGENTE: Riconfigurazione radio per {valvola_id}. Nuovo TX: {nuovo_intervallo}s")

            # 2. DECISIONE FISICA SULLA VALVOLA
            if pressione < self.soglia_critica and stato_attuale == 'CLOSED':
                comandi_downlink[valvola_id]['azione_valvola'] = 'OPEN'
                self.stato_attuatori[valvola_id] = 'OPEN'
                print(f"🧠 AGENTE [{current_time}s]: Crisi su {valvola_id}. Ordino: APERTURA.")

            elif pressione > (self.soglia_critica + 15) and stato_attuale == 'OPEN':
                comandi_downlink[valvola_id]['azione_valvola'] = 'CLOSED'
                self.stato_attuatori[valvola_id] = 'CLOSED'
                print(f"🧠 AGENTE [{current_time}s]: Rete stabile su {valvola_id}. Ordino: CHIUSURA.")

        return comandi_downlink

